"""backup.sh, run for real with HOME in tmp_path: it saves only the personal files it lists, and
restores them without overwriting what's already there."""

import os
import subprocess
import tarfile

from .conftest import REAL_POPEN, ROOT


def backup(home, *args):
    env = {**os.environ, "HOME": str(home)}
    p = REAL_POPEN(["bash", str(ROOT / "backup.sh"), *args], env=env, stdout=subprocess.PIPE,
                   stderr=subprocess.PIPE, text=True)
    out, err = p.communicate(timeout=60)
    return subprocess.CompletedProcess(p.args, p.returncode, out, err)


def write(home, rel, text):
    path = home / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


PERSONAL = {
    ".config/omarchy-settings/settings.json": '{"hyprland": {}}',
    ".local/state/desktop-notes/notes.json": '[{"text": "keep me", "done": false}]',
    ".config/desktop-notes/config.json": '{"opacity": 50}',
    ".config/omarchy/shell.json": '{"idle": {"lock": 600}}',
    ".config/hypr/hyprsunset.conf": "# Generated by Omarchy Settings",
}


def test_saves_only_the_personal_files(tmp_path):
    home = tmp_path / "home"
    for rel, text in PERSONAL.items():
        write(home, rel, text)
    write(home, ".config/hypr/hyprland.lua", "-- Omarchy's, not ours")
    write(home, ".ssh/id_ed25519", "secret")
    archive = tmp_path / "out.tar.gz"
    r = backup(home, str(archive))
    assert r.returncode == 0, r.stderr
    with tarfile.open(archive) as t:
        names = {m.name for m in t.getmembers() if m.isfile()}
    assert names == set(PERSONAL)


def test_list_shows_what_would_be_saved(tmp_path):
    home = tmp_path / "home"
    write(home, ".local/state/desktop-notes/notes.json", "[]")
    r = backup(home, "--list")
    assert r.stdout.split() == [".local/state/desktop-notes"]


def test_restore_puts_files_back_and_keeps_existing_ones(tmp_path):
    old, new = tmp_path / "old", tmp_path / "new"
    for rel, text in PERSONAL.items():
        write(old, rel, text)
    archive = tmp_path / "out.tar.gz"
    assert backup(old, str(archive)).returncode == 0
    fresh_shell = write(new, ".config/omarchy/shell.json", '{"fresh": true}')
    r = backup(new, "--restore", str(archive))
    assert r.returncode == 0, r.stderr
    for rel, text in PERSONAL.items():
        assert (new / rel).read_text() == text
    assert fresh_shell.with_name("shell.json.~1~").read_text() == '{"fresh": true}'


def test_nothing_to_save(tmp_path):
    home = tmp_path / "empty-home"  # not the sandbox's tmp_path/home, which already has folders
    home.mkdir()
    r = backup(home, str(tmp_path / "out.tar.gz"))
    assert r.returncode == 1 and "Nothing to save" in r.stderr
    assert not (tmp_path / "out.tar.gz").exists()
