"""Settings store: everything the app changes in Hyprland lives here and is rendered to
~/.config/hypr/omarchy_settings.lua, which hyprland.lua requires after looknfeel.lua."""

import json
import math
import re
import shutil
import time

from gi.repository import GLib

from .core import (CONFIG_DIR, HYPR_DIR, OMARCHY_PATH, STATE, hypr_option, lua_str, lua_syntax_error,
                   lua_table, lua_value, run_async, write_atomic)

SETTINGS_FILE = CONFIG_DIR / "settings.json"
LEGACY_FILE = CONFIG_DIR / "hyprland.json"
HYPR_LUA = HYPR_DIR / "omarchy_settings.lua"
HYPR_MAIN = HYPR_DIR / "hyprland.lua"
REQUIRE_LINE = 'require("hypr.omarchy_settings")'
CAPTURE_SUBMAP = "omarchy_settings_capture"
# Laptop panels: Omarchy turns these off and on with the lid, so the app never saves them off.
INTERNAL_PANEL = re.compile(r"^(eDP|LVDS|DSI)-")

HEADER = f"""-- Generated by Omarchy Settings (~/Work/omarchy-settings).
-- Edits here are overwritten; change settings in the app instead.
-- Each part runs on its own, so one bad entry can't take the rest of your config down.

local function section(name, fn)
  local ok, err = pcall(fn)
  if not ok then
    pcall(hl.exec_cmd, "omarchy-notification-send -u critical 'Omarchy Settings' "
      .. o.shell_quote(name .. ": " .. tostring(err)))
  end
end

-- Empty submap the app switches to while recording a new shortcut, so the
-- keys reach it instead of firing existing bindings. SUPER + ESCAPE leaves it.
section("capture submap", function()
  hl.define_submap({lua_str(CAPTURE_SUBMAP)}, function()
    hl.bind("SUPER + ESCAPE", hl.dsp.submap("reset"))
  end)
end)
"""


def _parse_animations():
    """Omarchy's default hl.animation lines as dicts, in order."""
    out = []
    try:
        text = (OMARCHY_PATH / "default/hypr/looknfeel.lua").read_text()
    except Exception:
        return out
    for line in text.splitlines():
        m = re.match(r"^hl\.animation\(\{(.*)\}\)\s*$", line.strip())
        if not m:
            continue
        d = {}
        for k, v in re.findall(r'(\w+)\s*=\s*("[^"]*"|[\w.]+)', m.group(1)):
            if v.startswith('"'):
                d[k] = v[1:-1]
            elif v in ("true", "false"):
                d[k] = v == "true"
            else:
                try:
                    d[k] = float(v)
                except ValueError:
                    d[k] = v
        if "leaf" in d:
            out.append(d)
    return out


DEFAULT_ANIMATIONS = _parse_animations()

OPACITY_RULE = re.compile(r'o\.window\(\s*\{\s*tag\s*=\s*"([^"]+)"\s*\}\s*,\s*\{[^}]*opacity\s*=\s*"([^"]+)"')


def omarchy_opacity_tags():
    """Tags Omarchy's window rules make less than fully opaque, e.g. default-opacity
    ("0.985 0.96") and the browser tags ("1.0 0.985"), read from its rule files."""
    tags = []
    base = OMARCHY_PATH / "default/hypr"
    for f in [base / "windows.lua", *sorted((base / "apps").glob("*.lua"))]:
        try:
            text = f.read_text()
        except Exception:
            continue
        for tag, value in OPACITY_RULE.findall(text):
            try:
                if any(float(x) < 1 for x in value.split() if x.replace(".", "", 1).isdigit()):
                    tags.append(tag)
            except ValueError:
                continue
    return sorted(set(tags)) or ["default-opacity"]


class Store:
    def __init__(self, on_result):
        self.on_result = on_result
        self.load_warning = None  # shown by the window once it can show toasts
        self.set_aside = False    # settings.json was unreadable and moved away
        data = self._load()

        def get(key, kind):
            value = data.get(key)
            if value is None:
                return kind()
            if not isinstance(value, kind):
                self.load_warning = self.load_warning or f"Ignored the unreadable “{key}” part of settings.json"
                return kind()
            return value

        self.values = get("hyprland", dict)        # "section:key" -> value
        self.cursor = get("cursor", dict)          # theme, size
        self.monitors = get("monitors", dict)      # output -> {enabled, mode, x, y, scale, transform}
        self.rules = get("rules", list)            # per-app window rules
        self.binds = get("binds", dict)            # disabled / rebinds / custom
        self.autostart = get("autostart", list)    # [{command, launch, enabled}]
        self.anim = get("animations", dict)        # factor, windows, workspaces
        self.pins = get("pins", dict)              # appearance kept across theme changes
        self.nightlight = get("nightlight", dict)  # temperature, schedule, start, end
        self.flags = get("flags", dict)            # omarchy_opacity: False = Omarchy's transparency off
        for key in ("disabled", "rebinds", "custom"):
            if not isinstance(self.binds.get(key), list):
                self.binds[key] = []
        if not isinstance(self.binds.get("disabled_info"), dict):
            self.binds["disabled_info"] = {}  # turned-off keys -> what was on them then
        dropped = self._clean()
        if dropped:
            self.load_warning = self.load_warning or (
                f"Ignored {dropped} unreadable entr{'y' if dropped == 1 else 'ies'} in settings.json")
        self._pending = None
        self._after_save = []
        self._warned_disabled = False
        # Rounding and gaps last sent to the shell; starts as loaded, so a plain save doesn't refresh it.
        self._shell_style = tuple(self.values.get(k) for k in SHELL_STYLE_KEYS)

    def _clean(self):
        """Drop entries the Lua generator can't handle, so a bad settings.json can't stop the
        app from starting. Returns how many were dropped."""
        def num(v, kind=float):
            # A real, finite number (JSON allows NaN and Infinity; true/false aren't numbers here).
            if isinstance(v, bool):
                return False
            try:
                kind(v)
                return math.isfinite(float(v))
            except (TypeError, ValueError, OverflowError):
                return False

        def finite(v):
            """No NaN or infinity anywhere inside a Hyprland option's value."""
            if isinstance(v, float):
                return math.isfinite(v)
            if isinstance(v, dict):
                return all(finite(x) for x in v.values())
            if isinstance(v, (list, tuple)):
                return all(finite(x) for x in v)
            return v is None or isinstance(v, (bool, int, str))

        dropped = 0

        def keep(items, ok):
            nonlocal dropped
            good = [x for x in items if ok(x)]
            dropped += len(items) - len(good)
            return good

        # An option that is also a section of another ("general:col" and "general:col:active_border")
        # can't be both a value and a table in the generated Lua.
        for opt in list(self.values):
            v = self.values[opt]
            if (not isinstance(opt, str) or not finite(v)
                    or any(other.startswith(opt + ":") for other in self.values if isinstance(other, str))):
                del self.values[opt]
                dropped += 1

        def rule_ok(r):
            return (isinstance(r, dict) and isinstance(r.get("class"), str)
                    and all(k not in r or num(r[k]) for k in ("opacity_active", "opacity_inactive"))
                    and ("workspace" not in r or r["workspace"] is None or isinstance(r["workspace"], str)
                         or num(r["workspace"], int)))

        self.rules = keep(self.rules, rule_ok)
        self.autostart = keep(self.autostart, lambda a: isinstance(a, dict) and isinstance(a.get("command"), str))
        b = self.binds
        b["disabled"] = keep(b["disabled"], lambda k: isinstance(k, str))
        b["rebinds"] = keep(b["rebinds"], lambda r: isinstance(r, dict) and all(
            isinstance(r.get(k), str) for k in ("old", "new", "line")))
        b["custom"] = keep(b["custom"], lambda c: isinstance(c, dict) and isinstance(c.get("keys"), str)
                           and isinstance(c.get("command"), str))
        for name in list(self.monitors):
            m = self.monitors[name]
            if not (isinstance(m, dict)
                    and all(k not in m or num(m[k], int if k in ("x", "y", "transform") else float)
                            for k in ("x", "y", "scale", "transform"))
                    and ("scale" not in m or float(m["scale"]) > 0)
                    and isinstance(m.get("mode", ""), str)):
                del self.monitors[name]
                dropped += 1
        if self.cursor.get("size") is not None and not num(self.cursor["size"], int):
            self.cursor.pop("size")
            dropped += 1
        if self.cursor.get("theme") is not None and not isinstance(self.cursor["theme"], str):
            self.cursor.pop("theme")
            dropped += 1
        if self.anim.get("factor") is not None and not (num(self.anim["factor"]) and float(self.anim["factor"]) > 0):
            self.anim.pop("factor")
            dropped += 1
        for k in ("windows", "workspaces"):
            if self.anim.get(k) is not None and not isinstance(self.anim[k], str):
                self.anim.pop(k)
                dropped += 1
        return dropped

    def _load(self):
        """Read settings.json (or the legacy file). An unreadable settings.json is set aside, not lost."""
        if SETTINGS_FILE.exists():
            try:
                data = json.loads(SETTINGS_FILE.read_text())
                if isinstance(data, dict):
                    return data
            except Exception:
                pass
            broken = SETTINGS_FILE.with_name(f"settings.json.broken-{int(time.time())}")
            try:
                SETTINGS_FILE.replace(broken)
            except Exception:
                pass
            self.load_warning = f"settings.json couldn't be read, so the app started fresh. The old file is {broken}"
            self.set_aside = True
            return {}
        try:
            data = json.loads(LEGACY_FILE.read_text())
            return data if isinstance(data, dict) else {}
        except Exception:
            return {}

    # ------------------------------------------------------------ values

    def current(self, option, default=None):
        if option in self.values:
            return self.values[option]
        v = hypr_option(option)
        return default if v is None else v

    def set(self, option, value):
        self.values[option] = value
        self.schedule_save()

    def reset(self, keys=None, prefix=None):
        """Drop overrides (all, only `keys`, or every key starting with `prefix`)."""
        if keys is None and prefix is None:
            self.values = {}
        for k in list(self.values):
            if (keys and k in keys) or (prefix and k.startswith(prefix)):
                self.values.pop(k, None)
        self.schedule_save()

    # ------------------------------------------------------------ persistence

    def refresh_rebinds(self, defaults):
        """Re-read each changed shortcut's line from Omarchy's current binding files.

        A rebind stores a copy of Omarchy's line; after an update that copy can be stale. Lines
        are refreshed from the binding at the same original key with the same description. A
        rebind whose binding is gone (or can no longer be rebound safely) is dropped. Returns
        (changed, dropped_descriptions).

        With no bindings read from Omarchy's files at all, nothing is changed: that means the files
        couldn't be read (moved, renamed, mid-update), and dropping then would lose every change."""
        by_key = {(b["keys"], b["description"]): b for b in defaults if b["line"]}
        if not by_key:
            return False, []
        kept, dropped, changed = [], [], False
        for rb in self.binds["rebinds"]:
            b = by_key.get((rb.get("old"), rb.get("description", "")))
            if not b or not b["rebindable"]:
                dropped.append(rb.get("description") or rb.get("old", "?"))
                changed = True
                continue
            if rb.get("line") != b["line"] or rb.get("guard") != b.get("guard"):
                rb["line"], rb["guard"] = b["line"], b.get("guard")
                changed = True
            kept.append(rb)
        self.binds["rebinds"] = kept
        # A key turned off here must not quietly unbind something new Omarchy put on it later.
        info = self.binds["disabled_info"]
        on_key = {}
        for b in defaults:
            if b["line"]:
                on_key.setdefault(b["keys"], []).append(b["description"])
        for keys in list(self.binds["disabled"]):
            was = info.get(keys)
            now = on_key.get(keys)
            if was is not None and now is not None and was not in now and was != " / ".join(now):
                self.binds["disabled"].remove(keys)
                info.pop(keys, None)
                dropped.append(f"{was} (off)")
                changed = True
        return changed, dropped

    def to_json(self):
        return {"hyprland": self.values, "cursor": self.cursor, "monitors": self.monitors,
                "rules": self.rules, "binds": self.binds, "autostart": self.autostart,
                "animations": self.anim, "pins": self.pins, "nightlight": self.nightlight, "flags": self.flags}

    def schedule_save(self, after=None):
        if after:
            self._after_save.append(after)
        if self._pending:
            GLib.source_remove(self._pending)
        self._pending = GLib.timeout_add(350, self._save)

    def sync_file(self):
        """Regenerate the Lua file when it is missing or was written by an older version of the app."""
        try:
            if HYPR_LUA.read_text() == self.render_lua():
                return
        except Exception:
            pass
        self.save_now()

    def save_now(self):
        if self._pending:
            GLib.source_remove(self._pending)
        self._save()

    def _save(self):
        self._pending = None
        callbacks, self._after_save = self._after_save, []
        try:
            lua = self.render_lua()
        except Exception as e:  # a value _clean didn't catch: report it, never stop the app
            lua, err = None, f"{type(e).__name__}: {e}"
        else:
            err = lua_syntax_error(lua)
        if err:
            # Nothing is written, so the last good settings.json and Lua file stay in place.
            self.on_result(f"Not saved, generated config is invalid: {err}")
            for cb in callbacks:
                cb()
            return False
        try:
            # Atomic: a crash mid-write leaves the previous file, never a truncated one.
            CONFIG_DIR.mkdir(parents=True, exist_ok=True)
            write_atomic(SETTINGS_FILE, json.dumps(self.to_json(), indent=2))
            write_atomic(HYPR_LUA, lua)
            state = ensure_required()
        except Exception as e:  # read-only file, full disk, missing folder…
            self.on_result(f"Couldn't save settings: {e}")
            for cb in callbacks:
                cb()
            return False
        if state == "disabled" and not self._warned_disabled:
            self._warned_disabled = True
            self.on_result("Changes aren't being loaded: the omarchy_settings line in "
                           "~/.config/hypr/hyprland.lua is commented out")

        style = tuple(self.values.get(k) for k in SHELL_STYLE_KEYS)
        style_changed = style != self._shell_style
        self._shell_style = style

        def checked(_c, out, _e):
            out = out.strip()
            self.on_result(None if not out or out == "no errors" else out)
            if style_changed:
                refresh_shell_style()  # after the reload, so the shell reads the new values
            for cb in callbacks:
                cb()

        run_async(["hyprctl", "reload"], lambda *_: run_async(["hyprctl", "configerrors"], checked))
        return False

    # ------------------------------------------------------------ lua

    def render_lua(self):
        out = [HEADER]

        def section(name, body):
            out.append(f"section({lua_str(name)}, function()")
            out.extend("  " + line for line in body)
            out.append("end)\n")

        tree = {}
        for opt, val in self.values.items():
            parts = opt.split(":")
            node = tree
            for p in parts[:-1]:
                node = node.setdefault(p, {})
            node[parts[-1]] = val
        # Keep tab-group borders matching the window borders.
        col = tree.get("general", {}).get("col", {})
        if col:
            group = tree.setdefault("group", {}).setdefault("col", {})
            if "active_border" in col:
                group["border_active"] = col["active_border"]
            if "inactive_border" in col:
                group["border_inactive"] = col["inactive_border"]
        for name, sub in tree.items():
            section(f"settings: {name}", ["hl.config({", f"  {name} = {{"] + lua_table(sub, 2) + ["  },", "})"])

        anim = self.render_animations()
        if anim:
            section("animations", anim)

        env = []
        if self.cursor.get("theme"):
            env.append(f'hl.env("XCURSOR_THEME", {lua_str(self.cursor["theme"])})')
            env.append(f'hl.env("HYPRCURSOR_THEME", {lua_str(self.cursor["theme"])})')
        if self.cursor.get("size"):
            env.append(f'hl.env("XCURSOR_SIZE", "{int(self.cursor["size"])}")')
            env.append(f'hl.env("HYPRCURSOR_SIZE", "{int(self.cursor["size"])}")')
        if env:
            section("cursor", env)

        for name, m in self.monitors.items():
            section(f"monitor {name}", [self.monitor_lua(name, m)])

        if self.flags.get("omarchy_opacity") is False:
            # Omarchy's window rules make most windows slightly see-through, and rules win over
            # the global opacity settings. Later rules win, so this comes after Omarchy's and
            # before the user's own per-app rules.
            section("Omarchy window transparency off", [
                f"hl.window_rule({lua_value({'match': {'tag': tag}, 'opacity': '1.00 1.00'})})"
                for tag in omarchy_opacity_tags()])

        for i, r in enumerate(self.rules):
            if r.get("enabled", True) and r.get("class"):
                line = self.rule_lua(r)
                if line:
                    section(f"window rule {r['class']}", [line])

        for keys in self.binds["disabled"]:
            section(f"unbind {keys}", [f"hl.unbind({lua_str(keys)})"])
        # Bindings that shared a key move together: one unbind of each key, then every line,
        # so a later unbind of the new key can't remove an earlier sibling.
        groups = {}
        for rb in self.binds["rebinds"]:
            groups.setdefault((rb["old"], rb["new"]), []).append(rb)
        for (old, new), members in groups.items():
            body = [f"hl.unbind({lua_str(old)})", f"hl.unbind({lua_str(new)})"]
            for rb in members:
                line = rb["line"].strip().replace(lua_str(old), lua_str(new), 1)
                # keep the `if` the line sat in (e.g. only when voxtype is installed)
                body.append(f"if {rb['guard']} then {line} end" if rb.get("guard") else line)
            section(f"shortcut {new}", body)
        for c in self.binds["custom"]:
            if not c.get("enabled", True) or not c.get("keys") or not c.get("command"):
                continue
            action = f"{{ launch = {lua_str(c['command'])} }}" if c.get("launch") else lua_str(c["command"])
            desc = lua_str(c.get("description") or c["command"])
            section(f"shortcut {c['keys']}", [f"hl.unbind({lua_str(c['keys'])})",
                                             f"o.bind({lua_str(c['keys'])}, {desc}, {action})"])

        starts = []
        for a in self.autostart:
            if a.get("enabled", True) and a.get("command"):
                fn = "o.launch_on_start" if a.get("launch", True) else "o.exec_on_start"
                starts.append(f"{fn}({lua_str(a['command'])})")
        if self.nightlight.get("schedule"):
            starts.append('o.launch_on_start("hyprsunset")')
        if starts:
            section("autostart", starts)
        return "\n".join(out)

    def render_animations(self):
        factor = float(self.anim.get("factor", 1.0) or 1.0)
        windows = self.anim.get("windows")        # None = Omarchy default
        workspaces = self.anim.get("workspaces")  # None = Omarchy default (off)
        if factor == 1.0 and not windows and not workspaces:
            return []
        lines = []
        for a in DEFAULT_ANIMATIONS:
            a = dict(a)
            if windows and a["leaf"] in ("windowsIn", "windowsOut"):
                a["style"] = windows if windows != "popin" else "popin 87%"
            if workspaces and a["leaf"] == "workspaces":
                if workspaces == "off":
                    a = {"leaf": "workspaces", "enabled": False}
                else:
                    a = {"leaf": "workspaces", "enabled": True, "speed": 4.0, "bezier": "easeOutQuint",
                         "style": workspaces}
            if "speed" in a and factor != 1.0:
                # Hyprland's speed is a duration (higher = slower), so divide by the speed factor.
                a["speed"] = round(max(0.1, a["speed"] / factor), 2)
            lines.append(f"hl.animation({lua_value(a)})")
        return lines

    @staticmethod
    def monitor_lua(name, m):
        # A docked laptop's panel is off live; a saved "off" would outlive undocking and
        # leave no screen at the next reload, so built-in panels are always written on.
        if not m.get("enabled", True) and not INTERNAL_PANEL.match(name):
            return f"hl.monitor({{ output = {lua_str(name)}, disabled = true }})"
        fields = {"output": name, "mode": m.get("mode") or "preferred",
                  "position": f"{int(m.get('x', 0))}x{int(m.get('y', 0))}" if "x" in m else "auto",
                  "scale": m.get("scale", 1)}
        if m.get("transform"):
            fields["transform"] = int(m["transform"])
        return f"hl.monitor({lua_value(fields)})"

    @staticmethod
    def rule_lua(r):
        cls = str(r["class"])
        regex = "^(" + re.sub(r"([\\.^$|?*+()\[\]{}])", r"\\\1", cls) + ")$"
        fields = {"match": {"class": regex}}
        if r.get("opacity_active") is not None or r.get("opacity_inactive") is not None:
            a = float(r.get("opacity_active", 1.0))
            i = float(r.get("opacity_inactive", a))
            fields["opacity"] = f"{a:.2f} {i:.2f}"
        if r.get("float"):
            fields["float"] = True
        if r.get("no_blur"):
            fields["no_blur"] = True
        ws = r.get("workspace")
        if ws:
            # A number from the app, or a name Hyprland understands (e.g. "special:steam").
            fields["workspace"] = str(int(ws)) if isinstance(ws, (int, float)) or str(ws).isdigit() else str(ws)
        if len(fields) == 1:
            return None
        return f"hl.window_rule({lua_value(fields)})"


ACTIVE_REQUIRE = re.compile(r'^[ \t]*require\("hypr\.omarchy_settings"\)', re.M)
COMMENTED_REQUIRE = re.compile(r'^[ \t]*--.*require\("hypr\.omarchy_settings"\)', re.M)
LOOKNFEEL_LINE = re.compile(r'^[ \t]*require\("hypr\.looknfeel"\)[^\n]*$', re.M)


def require_state():
    """'loaded', 'disabled' (commented out) or 'missing', without changing anything."""
    try:
        text = HYPR_MAIN.read_text()
    except Exception:
        return "missing"
    if ACTIVE_REQUIRE.search(text):
        return "loaded" if HYPR_LUA.exists() else "missing"
    return "disabled" if COMMENTED_REQUIRE.search(text) else "missing"


# Hyprland options Omarchy's shell copies for its own panels, menus and notifications
# (cornerRadius from decoration:rounding, edge gap from general:gaps_out).
SHELL_STYLE_KEYS = ("decoration:rounding", "general:gaps_out")


def refresh_shell_style():
    """Make Omarchy's shell re-read rounding and gaps from Hyprland.

    The shell only reads them at startup and when a theme is applied, so popups kept their old
    corners after a change. This sends the current theme exactly as `omarchy theme set` does,
    which changes nothing else and makes the shell refresh its style."""
    import base64
    theme = STATE / "current/theme"
    payload = []
    for name in ("colors.toml", "shell.toml"):
        try:
            payload.append(base64.b64encode((theme / name).read_bytes()).decode())
        except Exception:
            payload.append("")
    if not payload[0]:
        return  # no current theme to re-send
    run_async(["omarchy-shell", "shell", "applyTheme", *payload])


def ensure_required():
    """Make hyprland.lua load our generated file (once, with a backup).

    Returns "loaded" when the require line is active (or was just added), "disabled" when
    the user commented it out (respected: we never re-add it), or None when there is no
    hyprland.lua."""
    try:
        text = HYPR_MAIN.read_text()
    except Exception:
        return None
    if ACTIVE_REQUIRE.search(text):
        return "loaded"
    if COMMENTED_REQUIRE.search(text):
        return "disabled"
    shutil.copy2(HYPR_MAIN, HYPR_MAIN.with_name(f"hyprland.lua.bak.{int(time.time())}"))
    anchor = LOOKNFEEL_LINE.search(text)
    if anchor:
        text = text[:anchor.end()] + f"\n{REQUIRE_LINE}" + text[anchor.end():]
    else:
        text += f"\n{REQUIRE_LINE}\n"
    HYPR_MAIN.write_text(text)
    return "loaded"
